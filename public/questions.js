function buildPrompt(answers) {
  var a = answers || {};
  function v(k) { return (a[k] || "").trim() || "(not given)"; }
  return [
    "You are an expert online course architect. Build a complete course outline from my answers below.",
    "",
    "MY ANSWERS",
    "What I can teach: " + v("expertise"),
    "Who it is for: " + v("ideal_client"),
    "Where they are stuck: " + v("problem"),
    "What they can do at the end: " + v("bold_promise"),
    "Format: " + v("format"),
    "Who delivers it: " + v("delivered_by"),
    "My steps from stuck to done:",
    v("steps"),
    "What I do differently: " + v("unique_approach"),
    "Number of lessons: " + v("session_count"),
    "Minutes per lesson: " + v("session_minutes"),
    "A result or story I can point to: " + v("proof"),
    "Handouts or tools I already have: " + v("resources"),
    "Next step after the course: " + v("next_step"),
    "",
    "RULES",
    "1. Give the course a short, concrete name. Write one bold promise sentence with a clear result.",
    "2. Turn my steps into modules, in order. Spread exactly " + v("session_count") + " lessons across them.",
    "3. Every lesson has three parts: Teach (I explain), Do (the student acts), Review (the student checks the result). The three minute values must add up to " + v("session_minutes") + ".",
    "4. Name my unique approach if I did not name it. Say how to visualize it and why it works.",
    "5. Give every lesson a relevance line, a rationale, a search keyword, a first-sentence hook, a closing CTA, and at least one resource or handout. Use the handouts I already have where they fit.",
    "6. Give every lesson a YouTube title (max 70 characters, keyword near the front, no clickbait) and a short YouTube description.",
    "7. playlist_position counts lessons from 1 across the whole course.",
    "8. The last lesson's CTA points to my next step.",
    "9. Write in plain English. No emojis. Do not use dashes as sentence punctuation.",
    "",
    "OUTPUT",
    "Reply with one JSON object and nothing else. No intro, no explanation, no code fence. Use exactly this shape and these field names:",
    "",
    OUTLINE_SHAPE
  ].join("\n");
}
